package gatekeeper

import (
	"github.com/cosmosdevops/kube-policy-mcp/internal/engines"
	"github.com/cosmosdevops/kube-policy-mcp/internal/policy"
)

// EngineName is the name this adapter registers under.
const EngineName = "gatekeeper"

func init() {
	engines.Register(engines.Registration{
		Name:             EngineName,
		Title:            "OPA Gatekeeper",
		Description:      "Evaluates Gatekeeper constraints and their ConstraintTemplates (Rego or Kubernetes CEL) with the embedded Gatekeeper constraint framework, including constraint matching, parameters, enforcement actions and expansion templates.",
		SourceFormat:     "A directory of YAML or JSON files holding ConstraintTemplate resources and the constraints that use them. It may also hold ExpansionTemplate and Config resources.",
		NativeExceptions: "A Config resource (config.gatekeeper.sh) whose spec.match excludes namespaces from the webhook process. A constraint can also leave resources out with spec.match.",
		Limitations: []string{
			"A ConstraintTemplate enforces nothing by itself. Each constraint is one policy; a template that no constraint uses is only reported as a load warning.",
			"A constraint and its template must be in the same source.",
			"Templates that read data.inventory need context.resources. Without it the result is unknown.",
			"Templates that call external_data are not run, because that needs network access.",
			"Mutators (Assign, AssignMetadata, ModifySet, AssignImage) are only applied to resources generated by an ExpansionTemplate, as in gator. Submitted manifests are checked as written.",
			"Evaluation uses the admission enforcement point. Audit-only actions are not reported as violations.",
		},
		Module: "github.com/open-policy-agent/gatekeeper/v3",
		New:    func() policy.Engine { return New() },
	})
}
